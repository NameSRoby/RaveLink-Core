const catalog = Object.freeze(fields.map(Object.freeze));
function behaviors(input = {}) {
  if (
    !input ||
    typeof input !== "object" ||
    Array.isArray(input) ||
    Object.keys(input).some((k) => !catalog.some((f) => f.id === k))
  )
    throw Error("invalid_music_behaviors");
  const result = {};
  for (const f of catalog) {
    const v = Object.hasOwn(input, f.id) ? input[f.id] : f.value;
    if (
      f.type === "boolean" ? typeof v !== "boolean" : !Number.isFinite(v) || v < f.min || v > f.max
    )
      throw Error("invalid_music_behaviors");
    if (f.choices && !Object.hasOwn(f.choices, v)) throw Error("invalid_music_behaviors");
    result[f.id] = v;
  }
  return result;
}
module.exports = { catalog, behaviors };
