test("narrow source hooks preserve unrelated actions and capture middleware dispatch for metadata and append", async () => {
  const runtime = fs.readFileSync(path.join(integration, "renderer-runtime.js"), "utf8");
  const fixtureSource =
    "function makeAction(e,t){function n(...n){if(t){let r=t(...n);return{type:e,payload:r.payload,...`meta`in r&&{meta:r.meta}}}return{type:e,payload:n[0]}}return n.type=e,n}" +
    ";globalThis.make=makeAction;globalThis.enhance=(i,a)=>({...i,dispatch:a});";
  const patched = transform(fixtureSource);
  assert.equal(patched.actionHooks, 1);
  assert.equal(patched.storeHooks, 1);
  const context = vm.createContext({ setTimeout, clearTimeout });
  vm.runInContext(runtime + patched.code, context);
  const hooks = context.__ravelinkTidal,
    make = context.make;
  const names = [
    "content/LOAD_SINGLE_MEDIA_ITEM",
    "content/LOAD_SINGLE_MEDIA_ITEM_SUCCESS",
    "content/LOAD_SINGLE_MEDIA_ITEM_FAIL",
    "playQueue/ADD_MEDIA_ITEMS_TO_QUEUE",
    "search/SEARCH_FOR",
    "search/SEARCH_RESULT_SUCCESS",
    "search/SEARCH_RESULT_FAIL",
  ];
  const creators = Object.fromEntries(names.map((name) => [name, make(name)]));
  let bareCalls = 0,
    enhancedCalls = 0;
  const store = {
    getState: () => ({ playQueue: { elements: [] }, activePlayer: {} }),
    subscribe() {},
    dispatch() {
      bareCalls++;
    },
  };
  context.enhance(store, (action) => {
    enhancedCalls++;
    if (action.type === names[0]) creators[names[1]]({ mediaItem: { id: "123" } });
  });
  assert.equal(hooks.ready(), true);
  const result = await hooks.redux.interceptActionResp(
    () => hooks.redux.actions[names[0]]({ id: "123" }),
    new Set(),
    [names[1]],
    [names[2]],
    { timeoutMs: 100 },
  );
  assert.equal(result.mediaItem.id, "123");
  assert.equal(bareCalls, 0);
  assert.equal(enhancedCalls, 1);
  const unrelated = make("unrelated");
  assert.equal(unrelated({ test: true }).type, "unrelated");
  assert.equal(hooks.redux.actions["user/LOGIN"], undefined);
  const unloads = new Set();
  const canceled = hooks.redux.interceptActionResp(() => {}, unloads, [names[1]], [], {
    timeoutMs: 100,
  });
  for (const unload of unloads) unload();
  await assert.rejects(canceled, /stopped/);
  assert.equal(unloads.size, 0);
});
