  await new Promise((resolve) => setImmediate(resolve));
  assert.equal(started, true);
  assert.ok(installedPreload.filePath.endsWith("preload.cjs"));
  const asset = await handler({
    url: "https://desktop.tidal.com/assets/framework-example.js",
  });
  assert.equal(asset.headers.get("content-security-policy"), "script-src 'self'");
  assert.equal(asset.headers.has("etag"), false);
  assert.match(await asset.text(), /ravelinkInjected/);
  const login = await handler({
    url: "https://login.tidal.com/assets/login.js",
  });
  assert.doesNotMatch(await login.text(), /ravelinkInjected/);
  const mainFrame = { url: "https://desktop.tidal.com/" },
    sender = { id: 42, mainFrame };
  assert.equal((await ipc({ sender, senderFrame: mainFrame }, "next", {})).ok, true);
  assert.throws(
    () => ipc({ sender, senderFrame: { url: mainFrame.url } }, "next", {}),
    /sender_invalid/,
  );
  assert.throws(
    () => ipc({ sender: { id: 99, mainFrame }, senderFrame: mainFrame }, "next", {}),
    /sender_invalid/,
  );
